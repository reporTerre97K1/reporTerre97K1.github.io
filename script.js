const matrixCanvas = document.querySelector("#matrix-rain");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");

if (matrixCanvas) {
  const context = matrixCanvas.getContext("2d");

  if (context) {
    const glyphs = "アイウエオカキクケコサシスセソタチツテト012345789<>[]{}";
    const fontSize = 15;
    let canvasWidth = 0;
    let canvasHeight = 0;
    let pixelRatio = 1;
    let drops = [];
    let frameId = 0;
    let frameCount = 0;

    const resizeCanvas = () => {
      const bounds = matrixCanvas.getBoundingClientRect();
      pixelRatio = Math.min(window.devicePixelRatio || 1, 1.5);
      canvasWidth = bounds.width;
      canvasHeight = bounds.height;
      matrixCanvas.width = Math.round(canvasWidth * pixelRatio);
      matrixCanvas.height = Math.round(canvasHeight * pixelRatio);
      context.setTransform(pixelRatio, 0, 0, pixelRatio, 0, 0);
      context.fillStyle = "#03060b";
      context.fillRect(0, 0, canvasWidth, canvasHeight);
      drops = Array.from(
        { length: Math.ceil(canvasWidth / fontSize) },
        () => Math.random() * (canvasHeight / fontSize)
      );
    };

    const drawRain = () => {
      frameId = window.requestAnimationFrame(drawRain);
      frameCount += 1;
      if (frameCount % 3 !== 0) return;

      context.fillStyle = "rgba(3, 6, 11, 0.13)";
      context.fillRect(0, 0, canvasWidth, canvasHeight);
      context.font = `${fontSize}px monospace`;

      drops.forEach((drop, index) => {
        const glyph = glyphs[Math.floor(Math.random() * glyphs.length)];
        const x = index * fontSize;
        const y = drop * fontSize;
        const isHighlight = Math.random() > 0.985;
        context.fillStyle = isHighlight ? "rgba(109, 231, 255, 0.9)" : "rgba(42, 157, 255, 0.62)";
        context.fillText(glyph, x, y);

        if (y > canvasHeight && Math.random() > 0.975) drops[index] = 0;
        else drops[index] += 0.3 + Math.random() * 0.45;
      });
    };

    const stopRain = () => {
      if (frameId) window.cancelAnimationFrame(frameId);
      frameId = 0;
    };

    const syncRain = () => {
      stopRain();
      if (!reducedMotion.matches && document.visibilityState === "visible") {
        frameId = window.requestAnimationFrame(drawRain);
      }
    };

    resizeCanvas();
    syncRain();
    window.addEventListener("resize", resizeCanvas, { passive: true });
    window.addEventListener("resize", syncRain, { passive: true });
    document.addEventListener("visibilitychange", syncRain);

    if (typeof reducedMotion.addEventListener === "function") {
      reducedMotion.addEventListener("change", syncRain);
    } else if (typeof reducedMotion.addListener === "function") {
      reducedMotion.addListener(syncRain);
    }
  }
}

