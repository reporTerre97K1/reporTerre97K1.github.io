const sourceTextNodes = [];
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
let textNode;
while ((textNode = textWalker.nextNode())) {
  if (!textNode.nodeValue.trim() || textNode.parentElement.closest("[data-no-translate]")) continue;
  sourceTextNodes.push({ node: textNode, original: textNode.nodeValue });
}

const languageSwitcher = document.querySelector(".language-switch");
const languageButtons = [...document.querySelectorAll("[data-site-language]")];
const commandSearchInput = document.querySelector("#command-search");

function applyLanguage(language, persist = false) {
  if (!Object.hasOwn(interfaceText, language)) language = "uk";
  activeLanguage = language;
  const dictionary = pageCopy[language] || {};

  sourceTextNodes.forEach(({ node, original }) => {
    const trimmed = original.trim();
    const translated = dictionary[trimmed] || trimmed;
    const leading = original.match(/^\s*/)?.[0] || "";
    const trailing = original.match(/\s*$/)?.[0] || "";
    node.nodeValue = `${leading}${translated}${trailing}`;
  });

  document.documentElement.lang = language;
  document.title = {
    uk: "Рольовий бот для Telegram-груп",
    ru: "Ролевой бот для групп Telegram",
    en: "A roleplay bot for Telegram groups"
  }[language];
  const descriptions = {
    uk: "Знайомство з Telegram-ботом для групових чатів: ролі, репутація, економіка, роботи, ігри та інструменти модерації.",
    ru: "Telegram-бот для групповых чатов: роли, репутация, экономика, работа, игры и инструменты модерации.",
    en: "A Telegram group bot for roles, reputation, an in-game economy, jobs, games, and moderation tools."
  };
  document.querySelector('meta[name="description"]')?.setAttribute("content", descriptions[language]);
  document.querySelector(".site-nav")?.setAttribute("aria-label", interfaceText[language].navigation);
  document.querySelector(".brand")?.setAttribute("aria-label", interfaceText[language].home);
  document.querySelector(".hero-visual")?.setAttribute("aria-label", interfaceText[language].heroVisual);
  languageSwitcher?.setAttribute("aria-label", interfaceText[language].websiteLanguage);
  if (commandSearchInput) {
    commandSearchInput.placeholder = interfaceText[language].searchPlaceholder;
    commandSearchInput.setAttribute("aria-label", interfaceText[language].searchLabel);
  }
  if (menuButton) {
    const isOpen = menuButton.getAttribute("aria-expanded") === "true";
    menuButton.setAttribute("aria-label", isOpen ? interfaceText[language].menuClose : interfaceText[language].menuOpen);
  }

  languageButtons.forEach((button) => {
    const buttonLanguage = button.dataset.siteLanguage;
    button.setAttribute("aria-pressed", String(buttonLanguage === language));
    button.title = interfaceText[language].languageNames[buttonLanguage];
    button.setAttribute("aria-label", interfaceText[language].languageNames[buttonLanguage]);
  });

  if (filterCommands && commandSearchInput?.value.trim()) filterCommands();
  if (persist) {
    try {
      localStorage.setItem("telegrambot-website-language", language);
    } catch (_) {
      // Language switching still works for this page if storage is unavailable.
    }
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.siteLanguage, true));
});

let savedLanguage = "uk";
try {
  savedLanguage = localStorage.getItem("telegrambot-website-language") || "uk";
} catch (_) {
  // Use Ukrainian as the default when browser storage is unavailable.
}
applyLanguage(savedLanguage);
