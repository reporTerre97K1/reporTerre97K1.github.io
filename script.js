const menuButton = document.querySelector(".menu-toggle");
const navigation = document.querySelector("#site-nav");

if (menuButton && navigation) {
  menuButton.addEventListener("click", () => {
    const isOpen = menuButton.getAttribute("aria-expanded") === "true";
    menuButton.setAttribute("aria-expanded", String(!isOpen));
    menuButton.setAttribute("aria-label", isOpen ? interfaceText[activeLanguage].menuOpen : interfaceText[activeLanguage].menuClose);
    navigation.classList.toggle("is-open", !isOpen);
  });

  navigation.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      menuButton.setAttribute("aria-expanded", "false");
      menuButton.setAttribute("aria-label", interfaceText[activeLanguage].menuOpen);
      navigation.classList.remove("is-open");
    });
  });
}

const commandSearch = document.querySelector("#command-search");
const commandCards = [...document.querySelectorAll(".command-card")];
const noResults = document.querySelector("#no-results");
const searchStatus = document.querySelector("#search-status");

if (commandSearch && commandCards.length) {
  filterCommands = () => {
    const query = commandSearch.value.trim().toLocaleLowerCase(activeLanguage);
    let visibleCount = 0;

    commandCards.forEach((card) => {
      const content = `${card.textContent} ${card.dataset.search || ""}`.toLocaleLowerCase(activeLanguage);
      const matches = !query || content.includes(query);
      card.hidden = !matches;
      if (matches) visibleCount += 1;
    });

    if (noResults) noResults.hidden = visibleCount !== 0;
    if (searchStatus) {
      searchStatus.textContent = query
        ? interfaceText[activeLanguage].found.replace("{count}", String(visibleCount))
        : "";
    }
  };

  commandSearch.addEventListener("input", filterCommands);
}

